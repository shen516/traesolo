    def crawl(self, league_id: str = 'WC', team_id: str = None) -> Dict:
        try:
            logger.info(f"Starting real player crawl for league: {league_id}")
            
            fifa_goals = self._get_fifa_player_goals()
            
            squad_players = self._generate_world_cup_squad()
            
            for player in squad_players:
                name = player['name']
                if name in fifa_goals:
                    player['goals'] = fifa_goals[name].get('goals', 0)
                    player['assists'] = fifa_goals[name].get('assists', 0)
            
            players_dict = {}
            for player in squad_players:
                players_dict[player['id']] = player
            
            logger.info(f"Successfully crawled {len(players_dict)} real players")
            return list(players_dict.values())
            
        except Exception as e:
            logger.error(f"Real player crawl failed: {str(e)}")
            return []

    def _get_fifa_player_goals(self) -> Dict:
        try:
            url = "https://api.fifa.com/api/v3/calendar/matches?tournamentId=255216&language=zh-CN"
            response = self.session.get(url, timeout=30)
            if response.status_code != 200:
                logger.warning(f"FIFA API request failed: {response.status_code}")
                return {}
            
            data = response.json()
            player_goals = {}
            
            for match in data.get('Results', []):
                home_team = match.get('Home', {})
                away_team = match.get('Away', {})
                
                for team_data in [home_team, away_team]:
                    for player in team_data.get('Players', []):
                        name = player.get('Name', '')
                        if name:
                            if name not in player_goals:
                                player_goals[name] = {'goals': 0, 'assists': 0}
                            player_goals[name]['goals'] += player.get('Goals', 0)
            
            logger.info(f"Found {len(player_goals)} players with goals from FIFA data")
            return player_goals
            
        except Exception as e:
            logger.error(f"Failed to get FIFA player goals: {str(e)}")
            return {}

